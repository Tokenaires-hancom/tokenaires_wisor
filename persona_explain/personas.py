def render_criteria_spec(criteria) -> str:
    """채점에 실제로 쓰인 기준 목록을 프롬프트 조각으로 만든다.

    scores.json의 styles[].criteria를 그대로 싣는다. 페르소나 본문에 적어 둔 목록과
    어긋날 수 있으므로, 이쪽이 최종 기준임을 명시한다.
    """
    lines = ["", "[채점에 실제로 쓰인 기준 — 이것이 최종 기준이다]"]
    for item in criteria:
        weight = item.get("weight")
        suffix = f" (가중치 {weight})" if weight else ""
        lines.append(f"- {item.get('label')}{suffix}: {item.get('detail')}")
    lines.append("위 목록과 페르소나 설명이 다르면 위 목록을 따른다.")
    return "\n".join(lines) + "\n"


def build_system_prompt(persona_key: str, chat_mode: bool = False,
                        criteria_spec=None, with_criteria: bool = False) -> str:
    """공통 규칙 + 대가별 프롬프트를 합쳐 시스템 프롬프트를 만든다.

    chat_mode면 멀티턴 대화용 방어 규칙(CHAT_RULES)을 붙인다.
    criteria_spec(scores.json의 styles[].criteria)을 주면 실제 채점 기준을 싣는다.
    with_criteria면 <기준판정> 블록 해석 규칙(CRITERIA_RULES)을 붙인다.
    """
    persona = PERSONAS.get(persona_key)
    if persona is None:
        raise ValueError(f"unknown persona: {persona_key} (choose from {list(PERSONAS)})")
    prompt = COMMON_RULES + "\n" + persona["body"]
    if criteria_spec:
        prompt += render_criteria_spec(criteria_spec)
    if with_criteria:
        prompt += CRITERIA_RULES
    if chat_mode:
        prompt += CHAT_RULES
    return prompt
